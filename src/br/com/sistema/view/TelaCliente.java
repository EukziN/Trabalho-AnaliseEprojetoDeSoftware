    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // TODO add your handling code here:
        String nome = txtNome.getText();
String cpf = txtCpf.getText();
String endereco = txtEndereco.getText();

if (nome.isEmpty() || cpf.isEmpty() || endereco.isEmpty()) {

    JOptionPane.showMessageDialog(
            this,
            "Preencha todos os campos!"
    );

    return;
}

try {

    clienteDAO.cadastrar(nome, cpf, endereco);

    JOptionPane.showMessageDialog(
            this,
            "Cliente cadastrado com sucesso!"
    );

    limparCampos();
    carregarTabela();

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            this,
            "Erro ao cadastrar cliente: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
        if (idClienteSelecionado == 0) {

    JOptionPane.showMessageDialog(
            this,
            "Selecione um cliente na tabela!"
    );

    return;
}

String nome = txtNome.getText();
String cpf = txtCpf.getText();
String endereco = txtEndereco.getText();

if (nome.isEmpty() || cpf.isEmpty() || endereco.isEmpty()) {

    JOptionPane.showMessageDialog(
            this,
            "Preencha todos os campos!"
    );

    return;
}

try {

    clienteDAO.atualizar(
            idClienteSelecionado,
            nome,
            cpf,
            endereco
    );

    JOptionPane.showMessageDialog(
            this,
            "Cliente atualizado com sucesso!"
    );

    limparCampos();
    carregarTabela();

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            this,
            "Erro ao atualizar cliente: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnEditarActionPerformed

