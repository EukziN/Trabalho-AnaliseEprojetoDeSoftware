    private void tabelaClientesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelaClientesMouseClicked
        // TODO add your handling code here:
        int linha = tabelaClientes.getSelectedRow();

if (linha >= 0) {

    idClienteSelecionado =
            Integer.parseInt(
                    tabelaClientes.getValueAt(linha, 0).toString()
            );

    txtNome.setText(
            tabelaClientes.getValueAt(linha, 1).toString()
    );

    txtCpf.setText(
            tabelaClientes.getValueAt(linha, 2).toString()
    );

    txtEndereco.setText(
            tabelaClientes.getValueAt(linha, 3).toString()
    );
}
    }//GEN-LAST:event_tabelaClientesMouseClicked
    private void carregarTabela() {

    DefaultTableModel modelo =
            (DefaultTableModel) tabelaClientes.getModel();

    modelo.setRowCount(0);

    List<Object[]> clientes = clienteDAO.listarTodos();

    for (Object[] cliente : clientes) {
        modelo.addRow(cliente);
    }
}
